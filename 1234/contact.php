// REGISTER
function register() {
  const username = document.getElementById('reg-username').value.trim();
  const email = document.getElementById('reg-email').value.trim();
  const password = document.getElementById('reg-password').value;
  const msg = document.getElementById('register-msg');

  msg.textContent = '';

  if (!username || !email || !password) {
    msg.textContent = 'Please fill all fields';
    return;
  }

  if (localStorage.getItem(username)) {
    msg.textContent = 'Username already exists';
    return;
  }

  localStorage.setItem(username, JSON.stringify({ email, password }));

  msg.style.color = 'green';
  msg.textContent = 'Registration successful!';

  // Clear fields
  document.getElementById('reg-username').value = '';
  document.getElementById('reg-email').value = '';
  document.getElementById('reg-password').value = '';

  setTimeout(showLogin, 1000);
}


// LOGIN
function login() {
  const loginVal = document.getElementById('login-username').value.trim();
  const password = document.getElementById('login-password').value;
  const msg = document.getElementById('login-msg');

  msg.textContent = '';

  const storedUser = localStorage.getItem(loginVal);

  if (storedUser) {
    const user = JSON.parse(storedUser);

    if (user.password === password) {
      localStorage.setItem('currentUser', loginVal);

      document.getElementById('auth-overlay').style.display = 'none';
      showUser(loginVal);

    } else {
      msg.textContent = 'Incorrect username or password';
    }

  } else {
    // Check email login
    let found = null;

    for (let i = 0; i < localStorage.length; i++) {
      const key = localStorage.key(i);

      try {
        const data = JSON.parse(localStorage.getItem(key));
        if (data.email === loginVal) {
          found = { key, ...data };
          break;
        }
      } catch (e) {}
    }

    if (found && found.password === password) {
      localStorage.setItem('currentUser', found.key);

      document.getElementById('auth-overlay').style.display = 'none';
      showUser(found.key);

    } else {
      msg.textContent = 'Incorrect username or password';
    }
  }

  // Clear fields always
  document.getElementById('login-username').value = '';
  document.getElementById('login-password').value = '';
}


// SHOW USER IN HEADER
function showUser(username){
  const authArea = document.querySelector('.header__right__auth');

  if(authArea){
    authArea.innerHTML = `
      <span style="margin-right:10px;">Welcome, ${username}</span>
      <a href="#" onclick="logout()">Logout</a>
    `;
  }
}


// LOGOUT
function logout(){
  localStorage.removeItem('currentUser');
  location.reload();
}


